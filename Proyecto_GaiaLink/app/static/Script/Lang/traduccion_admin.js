document.addEventListener("DOMContentLoaded", () => {
    const idiomaGuardado = localStorage.getItem("idioma") || "es";
    const btn = document.getElementById("btnIdiomaUnico");
    const texto = document.getElementById("textoIdioma");
    const icono = document.getElementById("iconoIdioma");

    const idiomas = ["es", "en", "fr"];
    const nombres = { es: "Español", en: "English", fr: "Français" };
    const iconos = {
        es: "/static/img/Español.svg",
        en: "/static/img/Ingles.svg",
        fr: "/static/img/Frances.svg"
    };

    let indice = 0;

    if (idiomaGuardado && idiomas.includes(idiomaGuardado)) {
        indice = idiomas.indexOf(idiomaGuardado);
    }

    ActualizarBoton(idiomas[indice]);
    CambiarIdioma(idiomas[indice]);
    btn.addEventListener("click", () => {
        indice = (indice + 1) % idiomas.length;
        const nuevoIdioma = idiomas[indice];

        ActualizarBoton(nuevoIdioma);
        CambiarIdioma(nuevoIdioma);
    });

    function ActualizarBoton(idioma) {
        texto.textContent = nombres[idioma];
        icono.src = iconos[idioma];
        localStorage.setItem("idioma", idioma);
    }    
});
