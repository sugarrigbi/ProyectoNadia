function ActualizarBotonIdioma(idioma){
    const nombres = {
        es: "Español",
        en: "English",
        fr: "Français"
    };
    const iconos = {
        es: "/Statics/img/Español.svg",
        en: "/Statics/img/Ingles.svg",
        fr: "/Statics/img/Frances.svg"
    };
    document.getElementById("textoIdioma").textContent = nombres[idioma];
    document.getElementById("iconoIdioma").src = iconos[idioma];
}
function CambiarIdioma(idioma){
    function getValor(obj, path){
        return path.split('.').reduce((acc, key) => acc && acc[key], obj) || '';
    }
    document.querySelectorAll("[data-lang]").forEach(el =>{
        const clave = el.getAttribute("data-lang");
        const valor = getValor(Traducciones[idioma], clave);
        if(!valor) return;
        const tag = el.tagName.toLowerCase();
        if (tag === "input" && el.type === "submit"){
            el.value = valor;
        }
        else if (tag === "input" || tag === "textarea"){
            el.placeholder = valor;
        }
        else{
            el.innerHTML = valor;
        }
    });
    localStorage.setItem("idioma", idioma);
    ActualizarBotonIdioma(idioma);
}
document.addEventListener("DOMContentLoaded", () => {
    const idiomaGuardado = localStorage.getItem("idioma") || "es";
    CambiarIdioma(idiomaGuardado);
});